/** Build a deterministic 18-month S-curve around a current % progress. */
function buildSCurve(progress: number): SCurvePoint[] {
  const months: SCurvePoint[] = [];
  const start = new Date(2024, 0, 1);
  for (let i = 0; i < 18; i++) {
    const d = new Date(start.getFullYear(), start.getMonth() + i, 1);
    const tag = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}`;
    // logistic-ish ramp; planned slightly ahead of actual
    const t = i / 17;
    const planned = Math.round(100 / (1 + Math.exp(-8 * (t - 0.5))));
    const actualBase = Math.round(100 / (1 + Math.exp(-8 * (t - 0.55))));
    const cap = Math.min(progress, actualBase);
    months.push({ month: tag, planned, actual: cap });
  }
  return months;
}

